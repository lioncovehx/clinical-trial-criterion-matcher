"""Run a model over rows and turn each raw answer into a checked prediction record."""
import json

import torch
from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer

from src.data import parse_output, render_prompt, sentences


def load_model(model_dir: str, adapter: str | None = None):
    # Left padding: in a batch, every prompt must END at the same spot, because generation continues from there.
    tok = AutoTokenizer.from_pretrained(model_dir, padding_side="left")
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    model = AutoModelForCausalLM.from_pretrained(model_dir, dtype=torch.bfloat16, device_map="cuda")
    if adapter:
        # Folding the LoRA weights into the model makes inference as fast as a plain model.
        model = PeftModel.from_pretrained(model, adapter).merge_and_unload()
    return tok, model.eval()


@torch.inference_mode()  # no training here, so skip the memory cost of tracking gradients
def generate_batch(tok, model, prompts: list[str], max_new_tokens: int = 64) -> list[str]:
    inputs = tok(prompts, return_tensors="pt", padding=True).to("cuda")
    out = model.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False,
                         temperature=None, top_p=None, top_k=None)
    return tok.batch_decode(out[:, inputs.input_ids.shape[1]:], skip_special_tokens=True)


def explain(label: str, evidence: dict[int, str]) -> str:
    """Built from the label and the note's own sentences, so it cannot invent patient facts."""
    if not evidence:
        return f'Predicted "{label}". The model cited no sentence from the patient note.'
    quoted = " ".join(f'[{i}] "{text}"' for i, text in evidence.items())
    return f'Predicted "{label}" based on: {quoted}'


def make_record(raw: str, note: str, criterion_type: str, criterion_text) -> dict:
    sents = sentences(note)
    parsed = parse_output(raw, criterion_type, set(sents))
    evidence = {i: sents[i] for i in parsed["ids"]}  # copied by code, never generated by the model
    return {
        "criterion_type": criterion_type,
        "criterion": criterion_text,
        "pred_label": parsed["label"],
        "pred_ids": parsed["ids"],
        "evidence_text": list(evidence.values()),
        "explanation": explain(parsed["label"], evidence),
        "status": parsed["status"],
        "hallucinated": parsed["hallucinated"],
        "raw_output": raw,
    }


def predict_rows(tok, model, df, batch_size: int = 8) -> list[dict]:
    records = []
    for start in range(0, len(df), batch_size):
        batch = df.iloc[start:start + batch_size]
        prompts = [render_prompt(tok, r.note, r.criterion_type, r.criterion_text) for r in batch.itertuples()]
        for r, raw in zip(batch.itertuples(), generate_batch(tok, model, prompts)):
            records.append({"annotation_id": int(r.annotation_id), "gold_label": r.expert_eligibility,
                            "gold_ids": json.loads(r.expert_sentences),
                            **make_record(raw, r.note, r.criterion_type, r.criterion_text)})
        print(f"{len(records)}/{len(df)}", flush=True)
    return records
